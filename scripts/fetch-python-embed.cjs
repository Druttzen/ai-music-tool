#!/usr/bin/env node
/**
 * Fetch pinned Windows embeddable CPython + get-pip.py into
 * src-tauri/resources/python-embed/ for Tauri bundle.resources.
 *
 * Skip download when the zip already matches the pinned SHA-256.
 */
const crypto = require("crypto");
const fs = require("fs");
const https = require("https");
const path = require("path");

const root = path.join(__dirname, "..");
const destDir = path.join(root, "src-tauri", "resources", "python-embed");

/** @type {{ name: string, url: string, sha256: string }} */
const PYTHON_EMBED = {
  name: "python-3.12.10-embed-amd64.zip",
  url: "https://www.python.org/ftp/python/3.12.10/python-3.12.10-embed-amd64.zip",
  sha256: "4acbed6dd1c744b0376e3b1cf57ce906f9dc9e95e68824584c8099a63025a3c3",
};

/** get-pip.py (bootstrap.pypa.io) — pinned SHA-256; override with AIMC_GET_PIP_SHA256. */
const GET_PIP = {
  name: "get-pip.py",
  url: "https://bootstrap.pypa.io/get-pip.py",
  sha256:
    process.env.AIMC_GET_PIP_SHA256 ||
    "fb24e693bab954209a063d90953621412ccad4a500905a726286e038f508ddf6",
};

function sha256File(filePath) {
  const hash = crypto.createHash("sha256");
  hash.update(fs.readFileSync(filePath));
  return hash.digest("hex");
}

function download(url, dest) {
  return new Promise((resolve, reject) => {
    const tmp = `${dest}.partial`;
    const file = fs.createWriteStream(tmp);
    const get = (u, redirects = 0) => {
      https
        .get(u, (res) => {
          if (
            res.statusCode &&
            res.statusCode >= 300 &&
            res.statusCode < 400 &&
            res.headers.location &&
            redirects < 5
          ) {
            res.resume();
            get(res.headers.location, redirects + 1);
            return;
          }
          if (res.statusCode !== 200) {
            file.close();
            fs.unlinkSync(tmp);
            reject(new Error(`HTTP ${res.statusCode} for ${u}`));
            return;
          }
          res.pipe(file);
          file.on("finish", () => {
            file.close(() => {
              fs.renameSync(tmp, dest);
              resolve();
            });
          });
        })
        .on("error", (err) => {
          try {
            file.close();
            fs.unlinkSync(tmp);
          } catch {
            /* ignore */
          }
          reject(err);
        });
    };
    get(url);
  });
}

async function ensureAsset(asset) {
  const dest = path.join(destDir, asset.name);
  if (fs.existsSync(dest) && asset.sha256) {
    const got = sha256File(dest);
    if (got === asset.sha256.toLowerCase()) {
      console.log(`fetch-python-embed — ok ${asset.name}`);
      return;
    }
    console.warn(`fetch-python-embed — hash mismatch for ${asset.name}, re-downloading`);
    fs.unlinkSync(dest);
  } else if (fs.existsSync(dest) && !asset.sha256) {
    console.log(`fetch-python-embed — present ${asset.name} (no pin)`);
    return;
  }

  console.log(`fetch-python-embed — downloading ${asset.name}…`);
  await download(asset.url, dest);
  const got = sha256File(dest);
  if (asset.sha256 && got !== asset.sha256.toLowerCase()) {
    fs.unlinkSync(dest);
    throw new Error(`SHA-256 mismatch for ${asset.name}: got ${got}, expected ${asset.sha256}`);
  }
  if (!asset.sha256) {
    const pinPath = path.join(destDir, `${asset.name}.sha256`);
    fs.writeFileSync(pinPath, `${got}\n`);
    console.log(`fetch-python-embed — wrote ${path.relative(root, pinPath)} = ${got}`);
  }
  console.log(`fetch-python-embed — ok ${asset.name} (${got.slice(0, 12)}…)`);
}

async function main() {
  fs.mkdirSync(destDir, { recursive: true });
  const keep = path.join(destDir, ".gitkeep");
  if (!fs.existsSync(keep)) {
    fs.writeFileSync(
      keep,
      "# Generated by `npm run fetch:python-embed` — zip/get-pip are gitignored.\n",
    );
  }
  await ensureAsset(PYTHON_EMBED);
  // Prefer pinned hash from sibling .sha256 if present.
  const pinPath = path.join(destDir, `${GET_PIP.name}.sha256`);
  let getPip = { ...GET_PIP };
  if (!getPip.sha256 && fs.existsSync(pinPath)) {
    getPip.sha256 = fs.readFileSync(pinPath, "utf8").trim().split(/\s+/)[0];
  }
  await ensureAsset(getPip);
  // Manifest for Rust (version + filenames).
  fs.writeFileSync(
    path.join(destDir, "manifest.json"),
    `${JSON.stringify(
      {
        pythonVersion: "3.12.10",
        zip: PYTHON_EMBED.name,
        zipSha256: PYTHON_EMBED.sha256,
        getPip: GET_PIP.name,
      },
      null,
      2,
    )}\n`,
  );
  console.log(`fetch-python-embed — wrote ${path.relative(root, destDir)}`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
